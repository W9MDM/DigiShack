// Bundle the WSPR decoder thread into plain JavaScript.
//
//   npm run build:wspr-worker          writes lib/radio/wspr-worker.bundle.mjs
//   npm run check:wspr-worker          fails when the committed bundle is stale (in npm run check)
//
// WHY A BUNDLE. The decoder is TypeScript, and the bridge runs under tsx, so 1.188.0 spawned
// lib/radio/wspr-worker.ts straight into a worker thread on the measurement that a thread
// inherits the parent's loader flags. It does - on the Node 24 that measurement was taken
// on. The station runs Node 20, where loader hooks are not applied to worker threads, and
// every WSPR window there died with "Unknown file extension .ts". The FT8 worker is a plain
// .mjs for exactly this reason; the WSPR one becomes plain JavaScript by way of esbuild,
// with its imports (the codec, the demodulator, the metric table) folded in.
//
// COMMITTED, NOT BUILT ON THE BOX. A file that is always there cannot be forgotten by a
// deploy, and a stale one is caught by `npm run check` rather than by a quiet decode of
// old code. esbuild's output is deterministic for the same inputs and version, so the check
// is a byte comparison of a fresh in-memory build against the committed file.

import fs from "node:fs";
import path from "node:path";

import { build } from "esbuild";

const ENTRY = "lib/radio/wspr-worker.ts";
const OUT = "lib/radio/wspr-worker.bundle.mjs";
const BANNER = [
  "/* eslint-disable */",
  "// GENERATED by scripts/build-wspr-worker.ts from lib/radio/wspr-worker.ts and what it",
  "// imports. Do not edit. After changing the decoder run `npm run build:wspr-worker` and",
  "// commit the result; `npm run check:wspr-worker` fails while this file is stale.",
].join("\n");

async function bundle(): Promise<string> {
  const r = await build({
    entryPoints: [ENTRY],
    bundle: true,
    platform: "node",
    format: "esm",
    target: "node20",
    write: false,
    banner: { js: BANNER },
    legalComments: "none",
    logLevel: "warning",
    absWorkingDir: process.cwd(),
  });
  const out = r.outputFiles[0];
  if (!out) throw new Error("esbuild produced no output");
  return out.text;
}

const lf = (s: string) => s.replace(/\r\n/g, "\n");

async function main(): Promise<void> {
  const check = process.argv.includes("--check");
  const fresh = await bundle();
  const outPath = path.resolve(OUT);
  const current = fs.existsSync(outPath) ? lf(fs.readFileSync(outPath, "utf8")) : null;
  if (check) {
    if (current === fresh) {
      console.log(`  ok    ${OUT} is current (${fresh.length} bytes)`);
      return;
    }
    console.log(
      `  FAIL  ${OUT} is ${current === null ? "missing" : "stale"} - run npm run build:wspr-worker and commit it`,
    );
    process.exit(1);
  }
  if (current === fresh) {
    console.log(`${OUT} unchanged (${fresh.length} bytes)`);
    return;
  }
  fs.writeFileSync(outPath, fresh, "utf8");
  console.log(`wrote ${OUT} (${fresh.length} bytes)`);
}

main().catch((err) => {
  console.error(err instanceof Error ? err.message : String(err));
  process.exit(1);
});
