// Bundle a decoder thread into plain JavaScript.
//
//   npm run build:wspr-worker   (= tsx scripts/build-worker.ts wspr)     writes lib/radio/wspr-worker.bundle.mjs
//   npm run build:js8-worker    (= tsx scripts/build-worker.ts js8)      writes lib/radio/js8-worker.bundle.mjs
//   npm run check:wspr-worker / check:js8-worker (--check)                fail when the committed bundle is stale
//
// WHY A BUNDLE. The decoders are TypeScript, and the bridge runs under tsx, so the first
// WSPR release spawned the .ts worker straight into a thread on the measurement that a
// thread inherits the parent's loader flags. It does - on the Node 24 that measurement was
// taken on. The station runs Node 20, where loader hooks are not applied to worker threads,
// and every window there died with "Unknown file extension .ts". A worker is plain
// JavaScript, by way of esbuild, with its imports folded in.
//
// COMMITTED, NOT BUILT ON THE BOX. A file that is always there cannot be forgotten by a
// deploy, and a stale one is caught by `npm run check` rather than by a quiet decode of
// old code. esbuild's output is deterministic for the same inputs and version, so the check
// is a byte comparison of a fresh in-memory build against the committed file.

import fs from "node:fs";
import path from "node:path";

import { build } from "esbuild";

const WORKERS: Record<string, { entry: string; out: string }> = {
  wspr: { entry: "lib/radio/wspr-worker.ts", out: "lib/radio/wspr-worker.bundle.mjs" },
  js8: { entry: "lib/radio/js8-worker.ts", out: "lib/radio/js8-worker.bundle.mjs" },
};

async function bundle(entry: string, out: string): Promise<string> {
  const banner = [
    "/* eslint-disable */",
    `// GENERATED by scripts/build-worker.ts from ${entry} and what it imports. Do not`,
    `// edit. After changing the decoder run \`npm run build:${path.basename(out).replace("-worker.bundle.mjs", "")}-worker\``,
    "// and commit the result; the matching check:*-worker fails while this file is stale.",
  ].join("\n");
  const r = await build({
    entryPoints: [entry],
    bundle: true,
    platform: "node",
    format: "esm",
    target: "node20",
    write: false,
    banner: { js: banner },
    legalComments: "none",
    logLevel: "warning",
    absWorkingDir: process.cwd(),
  });
  const file = r.outputFiles[0];
  if (!file) throw new Error("esbuild produced no output");
  return file.text;
}

const lf = (s: string) => s.replace(/\r\n/g, "\n");

async function main(): Promise<void> {
  const name = process.argv[2] ?? "";
  const target = WORKERS[name];
  if (!target) {
    console.error(`which worker? one of: ${Object.keys(WORKERS).join(", ")}`);
    process.exit(2);
  }
  const check = process.argv.includes("--check");
  const fresh = await bundle(target.entry, target.out);
  const outPath = path.resolve(target.out);
  const current = fs.existsSync(outPath) ? lf(fs.readFileSync(outPath, "utf8")) : null;
  if (check) {
    if (current === fresh) {
      console.log(`  ok    ${target.out} is current (${fresh.length} bytes)`);
      return;
    }
    console.log(`  FAIL  ${target.out} is ${current === null ? "missing" : "stale"} - run npm run build:${name}-worker and commit it`);
    process.exit(1);
  }
  if (current === fresh) {
    console.log(`${target.out} unchanged (${fresh.length} bytes)`);
    return;
  }
  fs.writeFileSync(outPath, fresh, "utf8");
  console.log(`wrote ${target.out} (${fresh.length} bytes)`);
}

main().catch((err) => {
  console.error(err instanceof Error ? err.message : String(err));
  process.exit(1);
});
